import { spawnSync } from 'node:child_process';
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { transpile } from '@bytecodealliance/jco';
import { build } from 'esbuild';

// Build the Rust component's browser bindings and publish the application assets.
const root = fileURLToPath(new URL('../', import.meta.url));
const generated = join(root, 'packages/apple-code-browser/generated');
const output = join(root, 'apps/web/public/engine');
const component = join(root, 'target/component/apple-code.wasm');

/** Run a native build tool from the project root; stop the build on failure. */
function run(command: string, args: readonly string[]): void {
  const result = spawnSync(command, args, { cwd: root, stdio: 'inherit' });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

// 1. Fetch the pinned upstream WIT without changing its contents.
run('cargo', [
  'run',
  '--locked',
  '-p',
  'app-anatomy-xtask',
  '--',
  'wit',
  'fetch',
]);

// 2. Compile the Rust adapter and package its core Wasm as a component.
await mkdir(join(root, 'target/component'), { recursive: true });
run('cargo', [
  'build',
  '--locked',
  '-p',
  'workbench-component',
  '--target',
  'wasm32-unknown-unknown',
  '--release',
]);
run('wasm-tools', [
  'component',
  'new',
  join(root, 'target/wasm32-unknown-unknown/release/workbench_component.wasm'),
  '-o',
  component,
]);

// 3. Generate browser bindings, declarations and Wasm assets with jco's typed API.
// JSPI makes the selected Session methods asynchronous at the JavaScript boundary.
await rm(generated, { recursive: true, force: true });
const { files } = await transpile(await readFile(component), {
  name: 'apple-code',
  outDir: generated,
  instantiation: 'async',
  wasiShim: false,
  nodejsCompat: false,
  base64Cutoff: 0,
  namespacedExports: false,
  noComponentErrorWrapping: true,
  asyncMode: 'jspi',
  asyncExports: [
    'native#[method]session.choose-file',
    'native#[method]session.choose-folder',
    'native#[method]session.query-selection',
    'native#[method]session.open-file',
    'native#[method]session.open-directory',
    'native#[method]session.inspect',
  ],
});
// jco returns output paths including outDir, each paired with its generated bytes.
for (const [path, bytes] of Object.entries(files)) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, bytes);
}

// 4. Prepare the public directory and remove assets from previous implementations.
await mkdir(output, { recursive: true });
// Remove stale generated inputs so they cannot remain publicly accessible.
for (const path of [
  join(output, 'worker.mjs'),
  join(output, 'async-file-resource'),
  join(output, 'native-file-service'),
  join(root, 'apps/web/public/samples'),
]) {
  await rm(path, { recursive: true, force: true });
}

// 5. Bundle the browser adapter while keeping the generated jco bridge external.
await build({
  entryPoints: {
    native: join(root, 'packages/apple-code-browser/src/native/index.ts'),
  },
  outdir: output,
  outExtension: { '.js': '.mjs' },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2024',
  plugins: [
    {
      name: 'shared-component-bridge',
      setup(builder) {
        // Import the published jco bridge instead of bundling another copy.
        builder.onResolve({ filter: /\/generated\/apple-code\.js$/ }, () => ({
          path: './apple-code.js',
          external: true,
        }));
      },
    },
  ],
});

// 6. Publish the shared bridge and Wasm files referenced by the browser adapter.
for (const name of await readdir(generated)) {
  if (name.endsWith('.wasm') || name === 'apple-code.js')
    await cp(join(generated, name), join(output, name));
}
console.log('Rust component, shared jco bridge and native adapter built.');
