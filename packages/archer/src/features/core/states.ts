/**
 * Derived Atom: Ordered Array of Active Pair Keys
 *
 * A derived atom providing an array of all active pair keys, sourced from
 * `pairKeyRegistryAtom`. This `orderedPairKeysAtom` is crucial because it:
 * 1. Reflects the original insertion order of unique keys from the
 *    `pairKeyRegistryAtom` Set (JavaScript Sets iterate in insertion order, and
 *    spreading the Set preserves this).
 * 2. Provides an array format suitable for standard array operations (like
 *    `.map()` or `.forEach()`) used by other derived atoms, such as
 *    `edgeAtomsAtom` and `sourceEdgeMapAtom`.
 *
 * While `pairKeyRegistryAtom` (a Set) maintains insertion order, this
 * `orderedPairKeysAtom` serves as an intermediate derived state. It transforms
 * the Set of keys into an array, which is a more conventional and versatile
 * format for list iteration and transformation in subsequent derived atoms.
 *
 * Benefits of this intermediate array atom:
 * - Cleaner Consumer Logic:
 *   Derived atoms like `edgeAtomsAtom` can directly use `.map()` on the array
 *   from `orderedPairKeysAtom`, rather than needing
 *   `Array.from(get(pairKeyRegistryAtom)).map()`. This simplifies their
 *   implementation.
 *
 * - Decoupling and Focused Responsibility:
 *   `pairKeyRegistryAtom` focuses on unique key management.
 *   `orderedPairKeysAtom` focuses on providing an ordered, iterable sequence of
 *   these keys as an array. This separation aids in reasoning about each atom's
 *   specific role.
 *
 * - Stable Array Reference for `edgeAtomsAtom`:
 *   The array reference provided by `orderedPairKeysAtom` changes if and only
 *   if the underlying set of keys in `pairKeyRegistryAtom` changes. This change
 *   correctly signals `edgeAtomsAtom` to recompute, ensuring its own output
 *   array of atoms gets a new reference only when the input list of keys
 *   actually differs.
 *   This is beneficial for React's list reconciliation when
 *   `edgeAtomsAtom` is eventually used for rendering.
 */
export const orderedPairKeysAtom = atom<string[]>((get) => [
  ...get(pairKeyRegistryAtom),
]);

/**
 * Derived Atom: Array of Edge Atom Instances
 *
 * A derived atom that provides an array of all active `edgeFamily` atom
 * instances. Each element in this array is a `WritableAtom<SourceToTargetType |
 * null>` corresponding to a unique, direction-agnostic node pair.
 *
 * This array is primarily consumed by components like `<SvgArrowCanvas>`, which
 * iterate over this collection to render individual arrows. Each arrow
 * component would then subscribe directly to its specific atom from this array
 * to get edge data and re-render only when that specific edge's data changes.
 *
 * Core Benefit - Reference Stability of the Returned Array:
 * The array *instance* returned by this `edgeAtomsAtom` changes if and only if
 * the underlying `orderedPairKeysAtom` (the array of key strings) changes its
 * reference. This typically happens when a pair key is added or removed.
 * Modifying the *data within* an individual `edgeFamily` atom will NOT cause
 * `edgeAtomsAtom` to return a new array instance. This stability is vital for
 * React performance.
 *
 * Derivation Logic:
 * This atom derives its value by:
 * 1. Getting the current ordered array of pair key strings from
 *    `orderedPairKeysAtom`.
 * 2. Mapping these keys to their respective `edgeFamily` atom instances.
 *    (This creates an array of atom *references*, not their data values).
 *
 * Value Type:
 *   `WritableAtom<SourceToTargetType | null>[]`
 */
export const edgeAtomsAtom = atom((get) => {
  // Get the current, ordered list of pair key strings.
  const keys = get(orderedPairKeysAtom);

  /**
   * Map each key string to its corresponding atom instance from `edgeFamily`.
   * - `edgeFamily(k)` returns a stable atom reference for a given key 'k' due
   *   to atomFamily's internal caching.
   * - The result `atoms` is a new array instance containing these stable atom
   *   references.
   */
  const atoms = keys.map((k) => edgeFamily(k));

  /**
   * This `edgeAtomsAtom` recomputes (and thus `atoms` gets a new array
   * reference) ONLY if its dependency `keys` (derived from
   * `orderedPairKeysAtom`) changes its reference.
   *
   * Importantly, changes to the data *within* an individual `edgeFamily(k)`
   * atom (i.e., an edge's properties like label or style) do NOT trigger a
   * recomputation of `edgeAtomsAtom` itself. This is key to its reference
   * stability.
   */
  return atoms;
});

/**
 * Derived Atom: Map of Edge Data by Source ID
 *
 * A read-only derived atom constructing a lookup map:
 * `{ [sourceNodeId: string]: SourceToTargetType[] }`.
 *
 * Allows efficient retrieval of all outgoing edges' data for a source node.
 * E.g., `get(edgesBySourceIdAtom)["nodeX"]` yields an array of edges from
 * "nodeX".
 *
 * Key Differences from `edgeAtomsAtom`:
 * - `edgesBySourceIdAtom` provides a map of actual *edge data values*.
 * - `edgeAtomsAtom` provides an array of *edge atom instances*.
 * - This atom reads the values directly from individual `edgeFamily` atoms.
 * - It recomputes (returning a new map object) if the set of active pair keys
 *   changes or if any underlying edge data is updated.
 *
 * Derivation Logic:
 * Builds the map through these main steps:
 * 1. Initialize an empty map.
 * 2. Get the ordered list of active pair keys from `orderedPairKeysAtom`.
 * 3. For each key, retrieve its `SourceToTargetType` edge data. If data exists,
 *    add it to an array within the map, keyed by the edge's `source.id`.
 * 4. Return the populated map.
 *
 * Potential Use Cases:
 * - Pathfinding: Efficiently get all outgoing edges from the current node.
 * - Dependency Visualization: Show all direct dependents of a selected node.
 * - UI Details Pane: When a node is clicked, list its outgoing connections.
 *
 * Value Type:
 *   `Record<string, SourceToTargetType[]>`
 *   A map where keys are source node IDs (strings). Each value is an array of
 *   `SourceToTargetType` objects, representing all outgoing edges from that
 *   source. `SourceToTargetType` includes `source`, `target`, `label?`,
 *   `style?`, etc.
 *
 *   Example:
 *   If node "User" has edges to "Profile" and "Settings", and node "Profile"
 *   has an edge to "Avatar", the map might look like:
 *   ```
 *   {
 *     "User": [
 *       { source: {id:"User", ...}, target: {id:"Profile", ...}, label: "views" },
 *       { source: {id:"User", ...}, target: {id:"Settings", ...} }
 *     ],
 *     "Profile": [
 *       { source: {id:"Profile", ...}, target: {id:"Avatar", ...} }
 *     ]
 *     // ... other source nodes
 *   }
 *   ```
 */
export const edgesBySourceIdAtom = atom((get) => {
  // 1. Initialize an empty map for the results.
  const map: Record<string, SourceToTargetType[]> = {};

  // 2. Get the current, ordered list of all active pair key strings.
  const keys = get(orderedPairKeysAtom);

  // 3. For each key, retrieve its edge data and process if it exists.
  keys.forEach((k) => {
    // 3a. Get the actual edge data (SourceToTargetType or null) for this pair
    // key.
    const edge = get(edgeFamily(k));

    // 3b. If edge data exists, add it to the map, grouped by its source ID.
    if (edge) {
      // Ensure a bucket (array) exists for this edge's source ID.
      if (!map[edge.source.id]) {
        map[edge.source.id] = [];
      }
      // Add the edge data to the appropriate bucket.
      map[edge.source.id].push(edge);
    }
  });
  /**
   * 4. Return the populated map.
   *    This atom recomputes, yielding a new map reference, if:
   *    - The list of active `keys` (from `orderedPairKeysAtom`) changes.
   *    - The data within any `edgeFamily(k)` atom (for an active key 'k') is
   *      updated.
   */
  return map;
});
