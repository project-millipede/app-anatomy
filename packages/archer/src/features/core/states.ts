/**
 * Primitive Atom: Registry for Active Edge Pairs
 *
 * A primitive Set atom storing unique, canonical pair keys for active,
 * direction-agnostic node links. Keys are generated by `makePairKey()`,
 * ensuring a consistent "minId-maxId" format (see `makePairKey` JSDoc for
 * details).
 * JavaScript `Set` objects iterate elements in **insertion order**, a property
 * leveraged by `pairKeyListAtom`.
 *
 * This registry is the source of truth for *which* distinct node pairs have
 * connections. It's updated by action atoms when edges are added/removed.
 *
 * What is stored:
 * 1. One canonical key (e.g., "Alpha-Beta") per direction-agnostic node pair,
 *    regardless of initial edge definition (e.g., Alpha→Beta or Beta→Alpha).
 * 2. Only keys for pairs with at least one active edge.
 *
 * What is NOT stored:
 * 1. Multiple keys for the same pair (e.g., not both "Alpha-Beta" and
 *    "Beta-Alpha"); `makePairKey()` normalizes them.
 * 2. Specific edge orientation details within the key itself.
 *    - The *actual edge data* (like `source`, `target`, `doubleHeaded` status)
 *      is stored in the corresponding `edgeFamily(pairKey)` atom. This registry
 *      only tracks the *existence* of a link for the `pairKey`.
 *
 * @example
 * Processing ('Alpha', 'Beta') and ('Beta', 'Alpha') both result in "Alpha-Beta"
 * being the single, canonical key stored in this Set for that pair.
 */
export const pairKeyRegistryAtom = atomWithReset<Set<string>>(
  new Set<string>(),
);

/**
 * Atom Family: Manages Primitive Atoms for Individual Edge Data
 *
 * An `atomFamily` that creates and manages **one** primitive, writable atom for
 * each unique, direction-agnostic node pair (e.g., the pair A-B).
 * Each such atom holds the complete `SourceToTargetType` data representing the
 * connection (edge details, including directionality) *for that specific pair*.
 *
 * This `atomFamily` is parameterized by a canonical `pairKey` (a string like
 * "nodeA-nodeB") generated by `makePairKey()`. This `pairKey` uniquely
 * identifies the direction-agnostic link, and therefore, the single atom within
 * this family responsible for the A-B connection.
 *
 * Initial Value: Each new atom instance created by this family defaults to
 * `null`.
 *
 * What is stored within a single `edgeFamily("pairKey")` atom:
 * 1. The `SourceToTargetType` object for the node pair identified by `pairKey`.
 *    This object consolidates all information about the connection between
 *    these two nodes, including:
 *    - `source`: The `ArcherRef` of the source element (e.g., A).
 *    - `target`: The `ArcherRef` of the target element (e.g., B).
 *    - `label`, `style`: Optional visual properties.
 *    - `doubleHeaded`: A boolean. If edges A→B and B→A both exist conceptually,
 *      this flag within the *single* "A-B" pair's atom data is set to `true`.
 *      The atom does not store two separate edge objects for A→B and B→A;
 *      it stores one object representing the A-B pair, with `doubleHeaded`
 *      indicating bidirectionality.
 * 2. Or, `null` if no edge data has been set for this `pairKey`, or if an
 *    existing edge for this pair has been explicitly removed.
 *
 * What is NOT stored by an `edgeFamily("pairKey")` atom:
 * 1. Multiple, distinct edge objects for different orientations of the same
 *    pair. (e.g., not one object for A→B and another for B→A). All details for
 *    the A-B pair are consolidated into the single `SourceToTargetType` object
 *    held by `edgeFamily("A-B")`.
 * 2. Information about *other* node pairs. Each atom is isolated.
 *
 * Contrast with `pairKeyRegistryAtom`:
 * The registry stores *which* pairKeys (e.g., "A-B") exist. `edgeFamily("A-B")`
 * stores the *actual data object* for the A-B connection, including its
 * directionality via `doubleHeaded`.
 *
 * Key Characteristics and Behavior:
 * - One Atom per Direction-Agnostic Pair:
 *   `edgeFamily(makePairKey(A, B))` and `edgeFamily(makePairKey(B, A))` (which
 *   both yield the same `pairKey`, e.g., "A-B") will always resolve to the
 *   *exact same atom instance*. This is the cornerstone of the single source of
 *   truth for each pair.
 *
 * - Caching Mechanism:
 *   `atomFamily` internally uses a `WeakMap` to cache generated atoms, keyed by
 *   `pairKey`.
 *
 * - Atom Count Correlation:
 *   The number of active, cached atoms managed by this `edgeFamily` **is equal
 *   to** the number of unique keys present in `pairKeyRegistryAtom`.
 *   Example: If `pairKeyRegistryAtom` holds `{"A-B", "A-C"}` (2 keys), then
 *   there are exactly 2 corresponding primitive atoms active in `edgeFamily`:
 *   one for "A-B" and one for "A-C".
 *
 * - Garbage Collection:
 *   If a `pairKey` is removed from `pairKeyRegistryAtom` AND no active
 *   references to `edgeFamily(pairKey)` remain, the atom can be garbage
 *   collected.
 *
 * @param _pairKey (Parameter for `atomFamily`): The canonical string key
 *                 (e.g., "nodeA-nodeB") for the direction-agnostic node pair.
 * @returns A `WritableAtom<SourceToTargetType | null>` specific to the given
 *          `pairKey`, holding the consolidated edge data (or `null`).
 */
export const edgeFamily = atomFamily((_pairKey: string) =>
  atomWithReset<SourceToTargetType | null>(null),
);

